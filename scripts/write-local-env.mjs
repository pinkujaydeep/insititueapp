#!/usr/bin/env node
// Writes client/.env.local with the local Supabase URL and anon (public) key from `supabase status`.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const out = execSync("npx supabase status -o json", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
const status = JSON.parse(out.slice(out.indexOf("{")));

writeFileSync(
  new URL("../client/.env.local", import.meta.url),
  `# Generated by scripts/write-local-env.mjs - local development only\nVITE_SUPABASE_URL=${status.API_URL}\nVITE_SUPABASE_ANON_KEY=${status.ANON_KEY}\n`,
);
console.log("Wrote client/.env.local");
